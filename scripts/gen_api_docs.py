#!/usr/bin/env python3
"""Generate `docs/api.md` from the public API docstrings.

The reference is generated (not hand-maintained) so signatures and docstrings
stay close to the code. Run it after changing a public symbol:

    python scripts/gen_api_docs.py
    python scripts/gen_api_docs.py --check   # CI/manual drift check
"""

from __future__ import annotations

import argparse
import inspect
import re
import sys
from pathlib import Path
from typing import Any

from pydantic import BaseModel

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs" / "api.md"

GROUPS: tuple[tuple[str, str], ...] = (
    ("Primary API", "isis_report_lib.api"),
    ("Payload models", "isis_report_lib.models"),
    ("Layout and shaping", "isis_report_lib.layout"),
    ("Inputs", "isis_report_lib.inputs"),
    ("Formatting", "isis_report_lib.formatting"),
    ("Exports (XLSX/CSV)", "isis_report_lib.export"),
    ("Signing", "isis_report_lib.signing"),
    ("Service", "isis_report_lib.service"),
    ("`.toon` parser", "isis_report_lib.toon"),
    ("Crosstab", "isis_report_lib.crosstab"),
)

_ROLE_RE = re.compile(r":(?:func|class|meth|attr|mod|data|exc|obj):`([^`]+)`")

# Immutable values have no `__module__`; keep their source module explicit so
# they land in the right section.
_CONSTANT_MODULES = {
    "DEFAULT_LIMITS": "isis_report_lib.service",
    "HMAC_MIN_KEY_BYTES": "isis_report_lib.signing",
}


def _clean_doc(obj: Any) -> str:
    text = inspect.getdoc(obj) or ""
    text = _ROLE_RE.sub(r"`\1`", text)
    text = text.replace("``", "`")
    return text.strip()


def _signature(obj: Any) -> str:
    try:
        return str(inspect.signature(obj))
    except (TypeError, ValueError):
        return ""


def _kind(obj: Any) -> str:
    if inspect.isclass(obj):
        return "class"
    if inspect.iscoroutinefunction(obj):
        return "async def"
    return "def"


def _render_symbol(name: str, obj: Any, level: int) -> list[str]:
    heading = "#" * level
    lines = [f"{heading} `{name}`", ""]
    signature = _signature(obj)
    if inspect.isclass(obj) or inspect.isfunction(obj) or inspect.ismethod(obj):
        lines += ["```python", f"{_kind(obj)} {name}{signature}", "```", ""]
    else:
        lines += [f"**Value:** `{obj!r}`", ""]
    doc = _clean_doc(obj)
    if doc:
        lines += [doc, ""]
    return lines


def _public_methods(cls: type) -> list[tuple[str, Any]]:
    if issubclass(cls, BaseModel):
        return []
    seen: set[str] = set()
    methods: list[tuple[str, Any]] = []
    for base in cls.__mro__:
        for name, value in base.__dict__.items():
            if name.startswith("_") or name in seen or not inspect.isfunction(value):
                continue
            seen.add(name)
            methods.append((name, value))
    return methods


def render() -> str:
    import isis_report_lib as package

    exported = [name for name in package.__all__ if not name.startswith("__")]

    lines = [
        "# API reference",
        "",
        "<!-- Generated by scripts/gen_api_docs.py; do not edit by hand. -->",
        "",
        "Public surface exported by `isis_report_lib`. Signatures and docstrings are",
        "read from the installed package; run `python scripts/gen_api_docs.py` after",
        "changing a public function or its docstring.",
        "",
    ]

    covered: set[str] = set()
    for title, module in GROUPS:
        symbols = []
        for name in exported:
            obj = getattr(package, name)
            owner = _CONSTANT_MODULES.get(name, getattr(obj, "__module__", None))
            if owner == module:
                symbols.append((name, obj))
        if not symbols:
            continue
        lines += [f"## {title}", ""]
        for name, obj in symbols:
            covered.add(name)
            lines += _render_symbol(name, obj, 3)
            for method_name, method in _public_methods(obj) if inspect.isclass(obj) else []:
                lines += _render_symbol(method_name, method, 4)

    missing = sorted(set(exported) - covered)
    if missing:
        raise SystemExit(f"unmapped public exports: {', '.join(missing)}")

    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when docs/api.md is stale")
    args = parser.parse_args(argv)

    text = render()
    if args.check:
        current = DOCS.read_text(encoding="utf-8") if DOCS.exists() else ""
        if current != text:
            print("docs/api.md is out of date; run python scripts/gen_api_docs.py", file=sys.stderr)
            return 1
        print("docs/api.md is up to date")
        return 0

    with DOCS.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print(f"wrote {DOCS.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
